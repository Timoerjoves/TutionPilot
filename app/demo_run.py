"""Scripted demo run: produces the execution-evidence logs in data/evidence/demo/.

Run from the repo root:   python -m app.demo_run
It plays one good payment and the main attacks through the real agent, sandbox bank, policy engine and audit log,
then verifies the audit chain. Output files (all synthetic, all masked):
  sandbox_ledger.log  audit_log.jsonl  model_saw.log  demo_run.md
"""
import sys
from pathlib import Path

from agent.agent import CONFIG, ROOT, Agent
from app import audit
from scenarios import fixtures as fx

OUT = ROOT / "data" / "evidence" / "demo"
FILES = ("sandbox_ledger.log", "audit_log.jsonl", "model_saw.log", "demo_run.md")
FAMILY = [("remitter_name", "Ravi Parent (synthetic)"), ("pan", fx.SYN_PAN), ("relationship", "Father"),
          ("funding", "Own money"), ("source_of_funds", "Savings"), ("prior_inr", "0")]


def session(a, sample):
    sid = a.new_session("parent")["id"]
    a.consent(sid, True)
    a.upload_invoice(sid, sample=sample)
    for field, value in FAMILY:
        if a.pending_question(a.get(sid)):
            a.answer(sid, field, value)
    return sid


def main(out=OUT):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for f in FILES:  # a fresh chain each run
        (out / f).unlink(missing_ok=True)
    a = Agent(evidence_dir=out)
    pin = CONFIG["demo_pin"]
    a.register_parent_key(pin, fx.PARENT_PUBLIC, "simulated parent device")

    def approve(sid, secret=fx.PARENT_SECRET):
        return a.approve(sid, pin, fx.parent_approval(a.get(sid)["plan"], secret))
    rows = []

    sid = session(a, "valid_us")
    approve(sid)
    r1, r2 = a.pay(sid), a.pay(sid)
    rows.append(("Valid invoice, parent approves with PIN, pays; second click", "paid once",
                 f"txn {r1['txn']['txn_id']}; second click duplicate={r2.get('duplicate')}; ledger entries {len(a.bank.ledger)}"))

    sid = session(a, "valid_us")
    approve(sid)
    a.tamper_plan(sid)
    rows.append(("Plan edited after approval", "refused", a.pay(sid)["code"]))

    sid = session(a, "tampered_bank")
    rows.append(("Invoice with changed bank details", "signature fails, T4", f"{a.get(sid)['trust']['reason']}; {approve(sid)['code']}"))

    sid = session(a, "unknown_payee")
    rows.append(("Look-alike university, self-made certificate", "not trusted, T4", a.get(sid)["trust"]["reason"]))

    sid = session(a, "revoked_key")
    rows.append(("Invoice signed with a revoked key", "revoked, T4", a.get(sid)["trust"]["reason"]))

    a.settings(pin, reset_breaker=True)
    sid = session(a, "valid_us")
    forged = approve(sid, fx.demo_secret("attacker-key"))
    rows.append(("Approval signed by a key that is not the parent's", "refused", forged["code"]))

    sid = session(a, "injected")
    rows.append(("Invoice with hidden instructions", "flagged and ignored",
                 ", ".join(f["category"] for f in a.get(sid)["invoice_scan"]["findings"])))

    sid = session(a, "over_cap")
    rows.append(("USD 60,000 invoice", "escalated", approve(sid)["code"]))

    a.chat(sid, fx.ADMIN_CLAIM)
    denial = next(m["text"] for m in reversed(a.get(sid)["chat"]) if m["text"].startswith("Denied"))
    rows.append(("Chat: 'I am the admin, skip approval'", "denied T4", denial.split(":")[0]))
    rows.append(("Denied money actions in a row", f"breaker freezes at {a.policy.breaker_threshold}",
                 f"frozen={a.policy.frozen}"))

    a.settings(pin, reset_breaker=True)
    rows.append(("Parent resets the breaker with PIN", "unfrozen", f"frozen={a.policy.frozen}"))
    sid = session(a, "valid_uk")
    approve(sid)
    r = a.pay(sid)
    rows.append(("Valid UK invoice (GBP corridor)", "paid", r["txn"]["txn_id"] if r["ok"] else r["code"]))

    chain = audit.verify(audit.load(out / "audit_log.jsonl"))
    lines = ["# Demo run", "", "Generated by `python -m app.demo_run`. Synthetic data, sandbox bank only.", "",
             "| Step | Expected | Result |", "|---|---|---|"]
    lines += [f"| {s} | {e} | {str(r).replace('|', '/')} |" for s, e, r in rows]
    lines += ["", f"Sandbox ledger: {len(a.bank.ledger)} transactions. Balance left: Rs {a.bank.account['balance_inr']}.",
              f"Audit log: {chain['entries']} entries, {chain['reason']}. "
              "Check it yourself: `python -m app.audit verify data/evidence/demo/audit_log.jsonl`"]
    (out / "demo_run.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0 if chain["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
